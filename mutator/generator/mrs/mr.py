from abc import ABC, abstractmethod
from typing import List, Dict

class MetamorphicRelation(ABC):
    from transition_graph import GraphManager, ScriptPath

    def __init__(self, name: str, description: str, mr_type: str, graph_mgr: GraphManager):
        self.name = name
        self.description = description
        self.mr_type = mr_type
        self.graph_mgr = graph_mgr
    
    @abstractmethod
    def apply(self, original: ScriptPath) -> List[ScriptPath]:
        """
        Apply the metamorphic relation to generate test script variants based on the original path.

        Args:
            original: The original test script path.
        
        Returns:
            A list of test script variant paths generated by the MR.
        """
        pass
    
    
    def get_info(self) -> Dict[str, str]:
        return {
            'name': self.name,
            'description': self.description,
            'type': self.mr_type
        }
    
    def __str__(self) -> str:
        return f"{self.mr_type.upper()} MR: {self.name}"
    
    def __repr__(self) -> str:
        return f"MetamorphicRelation(name='{self.name}', type='{self.mr_type}')"